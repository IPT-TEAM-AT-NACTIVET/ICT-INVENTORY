-- In normal operation the schema is NOT created from this file by the
-- application at runtime. Instead it is derived from the JPA entities and
-- applied by Hibernate via `spring.jpa.hibernate.ddl-auto: update`
-- (see src/main/resources/application.yaml). This script documents the exact
-- DDL that Hibernate produces for the current entity model, plus the
-- `employee_id_seq` and initial ADMIN seed row, so the database can be
-- recreated manually from scratch and kept in sync with the code.
--
-- The purpose of this file is purely to SHOW how the database was created.
-- The runtime-managed schema migration script is src/main/resources/schema.sql
-- (with the "@@" statement separator, see application.yaml), which handles the
-- ALTER/DROP transitions between model versions.
--
-- Connection (application.yaml):
--   url       : jdbc:postgresql://localhost:5439/ict_inventory
