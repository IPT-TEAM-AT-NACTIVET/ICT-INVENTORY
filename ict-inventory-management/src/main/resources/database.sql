-- ---------------------------------------------------------------------------
-- 2. Sequence used by EmployeeIdGenerator to create unique Employee IDs
--    (format NCT-EMP-00001, ...). Same statement as in schema.sql; created
--    before Hibernate so it exists at registration time.
-- ---------------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS employee_id_seq;

-- ===========================================================================
-- TABLES (generated by Hibernate 6 from the JPA entities)
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- Zones (a zone contains many offices)
-- ---------------------------------------------------------------------------
CREATE TABLE zones (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL UNIQUE,
    code        VARCHAR(255) UNIQUE,
    description TEXT,
    status      VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- ---------------------------------------------------------------------------
-- Offices (belong to a zone, identified by office code within that zone)
-- ---------------------------------------------------------------------------
CREATE TABLE offices (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id     BIGINT NOT NULL REFERENCES zones (id),
    office_code VARCHAR(255) NOT NULL,
    status      VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_offices_zone_code UNIQUE (zone_id, office_code)
);

CREATE INDEX idx_offices_zone_id ON offices (zone_id);

-- ---------------------------------------------------------------------------
-- Directorates (top-level organisational unit a user belongs to)
-- ---------------------------------------------------------------------------
CREATE TABLE directorates (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL UNIQUE,
    code        VARCHAR(255) UNIQUE,
    description TEXT,
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- ---------------------------------------------------------------------------
-- Sections (belong to a directorate)
-- ---------------------------------------------------------------------------
CREATE TABLE sections (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(255) NOT NULL UNIQUE,
    code           VARCHAR(255) UNIQUE,
    description    TEXT,
    directorate_id BIGINT NOT NULL REFERENCES directorates (id),
    created_at     TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX idx_sections_directorate_id ON sections (directorate_id);

-- ---------------------------------------------------------------------------
-- Units (a user belongs to a unit)
-- ---------------------------------------------------------------------------
CREATE TABLE units (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL UNIQUE,
    code        VARCHAR(255) UNIQUE,
    description TEXT,
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- ---------------------------------------------------------------------------
-- Device types (asset categories)
-- ---------------------------------------------------------------------------
CREATE TABLE device_types (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    created_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

-- ---------------------------------------------------------------------------
-- Users
-- NOTE: A User does NOT have a zone/office (they belong to the Asset location).
--       role is stored as a string (enum): ADMIN.
--       username is kept internally on the entity and equals the email
--       (email is the public login/username); it is excluded from all DTOs.
-- ---------------------------------------------------------------------------
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id     VARCHAR(255) NOT NULL UNIQUE,
    full_name       VARCHAR(255) NOT NULL,
    username        VARCHAR(255) NOT NULL UNIQUE,
    email           VARCHAR(255) UNIQUE,
    password        VARCHAR(255) NOT NULL,
    phone_number    VARCHAR(255),
    role            VARCHAR(255) NOT NULL,
    enabled         BOOLEAN NOT NULL,
    setup_completed BOOLEAN NOT NULL DEFAULT FALSE,
    directorate_id  BIGINT REFERENCES directorates (id),
    section_id      BIGINT REFERENCES sections (id),
    unit_id         BIGINT REFERENCES units (id),
    created_at      TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at      TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX idx_users_directorate_id ON users (directorate_id);
CREATE INDEX idx_users_section_id     ON users (section_id);
CREATE INDEX idx_users_unit_id        ON users (unit_id);

-- ---------------------------------------------------------------------------
-- Assets
-- A User (owner/staff) belongs to directorate/section/unit, while an Asset
-- carries its PHYSICAL location as zone + office code (entered as freeform text).
-- ---------------------------------------------------------------------------
CREATE TABLE assets (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_number      VARCHAR(255) UNIQUE,
    serial_number     VARCHAR(255) UNIQUE,
    device_name       VARCHAR(255) NOT NULL,
    ownership_type    VARCHAR(255) NOT NULL,   -- OFFICE, PERSONAL
    device_status     VARCHAR(255) NOT NULL,   -- ACTIVE, DEFECTIVE
    device_type_id    BIGINT NOT NULL REFERENCES device_types (id),
    user_id           BIGINT NOT NULL REFERENCES users (id),
    zone_id           BIGINT REFERENCES zones (id),
    office               VARCHAR(100) NOT NULL,
    created_at        TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX idx_assets_user_id              ON assets (user_id);
CREATE INDEX idx_assets_device_type_id       ON assets (device_type_id);
CREATE INDEX idx_assets_zone_id              ON assets (zone_id);
CREATE INDEX idx_assets_device_status        ON assets (device_status);

-- ---------------------------------------------------------------------------
-- Audit logs
-- ---------------------------------------------------------------------------
CREATE TABLE audit_logs (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action                VARCHAR(255) NOT NULL,
    entity_type           VARCHAR(255) NOT NULL,
    entity_id             BIGINT,
    performed_by          VARCHAR(255),
    performed_by_user_id  BIGINT,
    description           TEXT,
    created_at            TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

